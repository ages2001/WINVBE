#!/usr/bin/env python3
"""
WINVBE - resources in the Windows 1.x/2.x display driver format.

Converts the artwork generated by mkres.py (res/*.bmp, *.cur, *.ico) into the
pre-3.0 resource layouts and writes them, plus the OEMBIN configuration
resources, to an output folder together with winvbe2.rc:

  cursor (type 1)  14 byte header: fmt, hotX, hotY, cx, cy, cbWidth, planes,
                   bits; AND mask then XOR mask, top-down
  bitmap (type 2)  16 byte header: 2, 0, cx, cy, cbWidth, planes, bits,
                   dword 0; top-down rows, word aligned, 1 = white
  icon   (type 3)  like cursors with fmt 1 (monochrome 32x32)
  OEMBIN 1         9 metric words + 13 default system colours
  OEMBIN FONTS     LOGFONTs of the OEM, ANSI fixed, ANSI variable and
                   system fonts
Usage: mkres2.py <res folder> <out folder> [oldwin1]
"""
import os
import struct
import sys

SRC = sys.argv[1]
OUT = sys.argv[2]
V1 = len(sys.argv) > 3 and sys.argv[3] == 'oldwin1'
os.makedirs(OUT, exist_ok=True)


def read_dib(data, off=0):
    """returns (w, h, bits, palette, rows top-down as lists of indices)"""
    hs, w, h, planes, bits = struct.unpack_from('<IiiHH', data, off)
    ncol = struct.unpack_from('<I', data, off + 32)[0] or (1 << bits)
    pal = [data[off + hs + i * 4: off + hs + i * 4 + 3] for i in range(ncol)]
    return hs, w, h, bits, pal, off + hs + ncol * 4


def unpack_rows(data, pos, w, h, bits):
    stride = ((w * bits + 31) // 32) * 4
    rows = []
    for y in range(h):
        r = data[pos + y * stride: pos + (y + 1) * stride]
        if bits == 1:
            rows.append([(r[x >> 3] >> (7 - (x & 7))) & 1 for x in range(w)])
        else:
            rows.append([(r[x >> 1] >> (4 if not x & 1 else 0)) & 15 for x in range(w)])
    rows.reverse()                      # DIBs are bottom-up
    return rows, pos + h * stride


def pack_mono(rows, w):
    wb = ((w + 15) // 16) * 2
    out = bytearray()
    for r in rows:
        b = bytearray(wb)
        for x, v in enumerate(r):
            if v:
                b[x >> 3] |= 0x80 >> (x & 7)
        out += b
    return bytes(out), wb


def bitmap(rid):
    d = open(os.path.join(SRC, f'b{rid}.bmp'), 'rb').read()
    hs, w, h, bits, pal, pos = read_dib(d, 14)
    assert bits == 1
    rows, _ = unpack_rows(d, struct.unpack_from('<I', d, 10)[0], w, h, 1)
    white = [1 if sum(pal[i]) >= 384 else 0 for i in range(2)]
    rows = [[white[v] for v in r] for r in rows]
    data, wb = pack_mono(rows, w)
    return struct.pack('<HHHHHBBI', 2, 0, w, h, wb, 1, 1, 0) + data


def icur(name, cursor):
    d = open(os.path.join(SRC, name), 'rb').read()
    n = struct.unpack_from('<H', d, 4)[0]
    best = None
    for i in range(n):
        w, h, nc, _, a, b, size, off = struct.unpack_from('<BBBBHHII', d, 6 + 16 * i)
        bits = struct.unpack_from('<H', d, off + 14)[0]
        if best is None or bits < best[2]:
            best = (off, (a, b) if cursor else (0, 0), bits)
    off, hot, bits = best
    hs, w, h2, bits, pal, pos = read_dib(d, off)
    h = h2 // 2
    xrows, pos = unpack_rows(d, pos, w, h, bits)
    arows, _ = unpack_rows(d, pos, w, h, 1)
    if bits != 1 or len(pal) != 2:      # colour image: threshold to black/white
        xrows = [[1 if sum(pal[v]) >= 384 else 0 for v in r] for r in xrows]
    else:
        xrows = [[1 if sum(pal[v]) >= 384 else 0 for v in r] for r in xrows]
    # a transparent pixel (AND=1) must have XOR=0 unless it inverts
    adata, wb = pack_mono(arows, w)
    xdata, _ = pack_mono(xrows, w)
    return hot, w, h, wb, adata + xdata


res = []                                # (type, id, file)

def drawn(w, h, black):
    """1 bpp bitmap w x h, black(x, y) -> pixel is black"""
    rows = [[0 if black(x, y) else 1 for x in range(w)] for y in range(h)]
    data, wb = pack_mono(rows, w)
    return struct.pack('<HHHHHBBI', 2, 0, w, h, wb, 1, 1, 0) + data


# Windows 1.x draws the zoom box at the right end of the caption at the
# bitmap's own size inside a box of the caption height (19 x 25 pixels with
# WINVBE's metrics; the 13 x 14 bitmaps of the EGA driver would leave most
# of it black), so these two are drawn at the box size
CAPBOX = (25, 19)
V1_BITMAPS = {
    # 32766: size box (window not zoomed) - corner of a window
    32766: lambda w, h: drawn(w, h, lambda x, y: (8 <= y <= 10 and x <= 14) or (9 <= x <= 14 and y >= 8)),
    # 32761: zoomed window - frame with the window filling its top-left part
    32761: lambda w, h: drawn(w, h, lambda x, y: x in (0, w - 1) or y in (0, h - 1) or (x <= 15 and y <= 10)),
}

for rid in range(32755 if not V1 else 32758, 32768):
    fn = f'b{rid}.bin'
    if V1 and rid in V1_BITMAPS:
        open(os.path.join(OUT, fn), 'wb').write(V1_BITMAPS[rid](*CAPBOX))
    else:
        open(os.path.join(OUT, fn), 'wb').write(bitmap(rid))
    res.append(('2', rid, fn))

cursors = [32512, 32513, 32514, 32515, 32516, 32640, 32641, 32642, 32643, 32644, 32645]
if V1:
    cursors = [32512, 32513, 32514, 32515, 32516, 32640, 32641]
for rid in cursors:
    (hx, hy), w, h, wb, data = icur(f'c{rid}.cur', True)
    fmt = 0x103 if 32642 <= rid <= 32645 else 3
    hdr = struct.pack('<HHHHHHBB', fmt, hx, hy, w, h, wb, 0, 0)
    fn = f'c{rid}.bin'
    open(os.path.join(OUT, fn), 'wb').write(hdr + data)
    res.append(('1', rid, fn))

for rid in [32512, 32513, 32514, 32515, 32516]:
    _, w, h, wb, data = icur(f'i{rid}.ico', False)
    hdr = struct.pack('<HHHHHHBB', 1, 0, 0, w, h, wb, 0, 0)
    fn = f'i{rid}.bin'
    open(os.path.join(OUT, fn), 'wb').write(hdr + data)
    res.append(('3', rid, fn))


def rgb(r, g, b):
    return bytes((r, g, b, 0))


# metrics (as in the Windows 1.x/2.x drivers) + default system colours in
# the classic look of each version:
#   2.x: blue caption, cyan menu bar and desktop, grey borders (13 colours:
#        scroll bar, desktop, active caption, inactive caption, menu,
#        window, frame, menu text, window text, caption text, active
#        border, inactive border, application workspace)
#   1.x: blue caption, yellow menu bar, green desktop / icon area
#        (10 colours, scroll bar ... caption text)
cfg = struct.pack('<9H', 18, 20, 2, 2, 1, 1, 0, 1, 1)
if V1:
    cols = [(255, 0, 0), (0, 255, 64), (0, 0, 255), (64, 64, 200), (255, 255, 0),
            (255, 255, 255), (0, 0, 0), (0, 0, 0), (0, 0, 0), (255, 255, 255)]
else:
    cols = [(63, 63, 63), (0, 255, 255), (0, 0, 255), (255, 255, 255), (0, 255, 255),
            (255, 255, 255), (0, 0, 0), (0, 0, 0), (0, 0, 0), (255, 255, 255),
            (127, 127, 127), (127, 127, 127), (0, 128, 255)]
cfg += b''.join(rgb(*c) for c in cols)
open(os.path.join(OUT, 'oem1.bin'), 'wb').write(cfg.ljust(80, b'\0'))


def logfont(h, w, charset, pitch, face):
    return struct.pack('<5h8B', h, w, 0, 0, 0, 0, 0, 0, charset, 0, 2, 2, pitch) + face.encode() + b'\0'


fonts = (logfont(12, 8, 255, 1, 'Terminal') + logfont(12, 9, 0, 1, 'Courier') +
         logfont(12, 9, 0, 2, 'Helv') + logfont(15, 8, 0, 1, 'System'))
open(os.path.join(OUT, 'fonts.bin'), 'wb').write(fonts.ljust(112, b'\0'))

rc = [f'{rid} {typ} PRELOAD MOVEABLE PURE {fn}' for typ, rid, fn in res]
rc.append('1 OEMBIN PRELOAD MOVEABLE PURE oem1.bin')
rc.append('FONTS OEMBIN PRELOAD MOVEABLE PURE fonts.bin')
open(os.path.join(OUT, 'winvbe2.rc'), 'w').write('\n'.join(rc) + '\n')
print('old format resources:', len(res) + 2)
